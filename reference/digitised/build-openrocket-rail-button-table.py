#!/usr/bin/env python3
"""Plan 0071 (D-108): build packages/physics/src/drag/openrocket-rail-button-table.ts (DRAG-23).

Reads reference/rockets/drag-probe/rail-button-table.csv, the rail button drag OpenRocket 24.12
computed for single buttons (tools/openrocket-harness/src/ProtuberanceProbe.java --cases, rows
tagged "table"). Each row gives one button's C_D A = deltaCd x refArea. Its coefficient K is C_D A
over the frontal area A = OD (base + flange) + ID (height - base - flange), and its abscissa is
eta = height / delta with delta = 0.37 x Re_x^-0.2, Re_x = V x / nu, x the button's front from the
nose tip and nu OpenRocket's kinematic viscosity at the probe's conditions (293.15 K, 101325 Pa;
reference/rockets/drag-probe/values.txt).

Run from the repository root:  python3 reference/digitised/build-openrocket-rail-button-table.py
"""
import csv

NU_OPENROCKET_STATIC = 1.52562878e-5
SOURCE = 'reference/rockets/drag-probe/rail-button-table.csv'
TARGET = 'packages/physics/src/drag/openrocket-rail-button-table.ts'


def sig(v: float) -> str:
    return repr(float(f'{v:.6g}'))


rows: dict[float, list[tuple[float, float]]] = {}
with open(SOURCE, newline='') as f:
    for r in csv.DictReader(f):
        if r['tag'] != 'table':
            continue
        x = float(r['noseLength']) + float(r['x'])
        h = float(r['height'])
        base, flange = float(r['base']), float(r['flange'])
        area = float(r['od']) * (base + flange) + float(r['id']) * (h - base - flange)
        k = float(r['deltaCd']) * float(r['refArea']) / area
        re = float(r['velocity']) * x / NU_OPENROCKET_STATIC
        eta = h / (0.37 * x * re ** -0.2)
        rows.setdefault(float(r['mach']), []).append((eta, k))

lines = []
for m in sorted(rows):
    pts = sorted(rows[m])
    lines.append(f'  [{sig(m)}, [{", ".join(f"[{sig(e)}, {sig(k)}]" for e, k in pts)}]],')

header = '''/**
 * DRAG-23 data (plan 0071, D-108): OpenRocket 24.12's rail button drag coefficient K against
 * eta = height / delta, one row per Mach number, measured as a black box (CLAUDE.md section 3) and
 * generated by reference/digitised/build-openrocket-rail-button-table.py from
 * reference/rockets/drag-probe/rail-button-table.csv. Do not edit by hand.
 *
 * K is one button's C_D·A over its frontal area; delta = 0.37 x Re_x^−0.2 with OpenRocket's
 * viscosity at the probe's conditions. Each row: [Mach, [[eta, K], ...]], eta ascending.
 */
// prettier-ignore
export const OPENROCKET_RAIL_BUTTON_TABLE: readonly (readonly [
  number,
  readonly (readonly [number, number])[],
])[] = [
'''
with open(TARGET, 'w') as f:
    f.write(header + '\n'.join(lines) + '\n];\n')
print(f'{len(rows)} Mach rows, {sum(len(v) for v in rows.values())} points')
